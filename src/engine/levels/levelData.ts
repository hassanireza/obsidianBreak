import type { BrickDefinition, BrickMaterial, LevelDefinition } from "../types";

/**
 * Levels are authored as text grids for readability. Each character
 * maps to a brick material and hit-point count, or to empty space.
 * `.` = empty, `q` = quartz(1hp), `a` = ash(2hp), `e` = ember(3hp),
 * `o` = obsidian (indestructible), `u` = aurora (1hp, always drops a power-up).
 */
const LEGEND: Record<string, { hp: number; material: BrickMaterial } | null> = {
  ".": null,
  q: { hp: 1, material: "quartz" },
  a: { hp: 2, material: "ash" },
  e: { hp: 3, material: "ember" },
  o: { hp: 99, material: "obsidian" },
  u: { hp: 1, material: "aurora" },
};

function parseGrid(rows: string[]): BrickDefinition[] {
  const bricks: BrickDefinition[] = [];
  rows.forEach((line, row) => {
    [...line].forEach((char, col) => {
      const entry = LEGEND[char];
      if (entry) bricks.push({ col, row, hp: entry.hp, material: entry.material });
    });
  });
  return bricks;
}

